-- ABOCCRIM - Esquema relacional PostgreSQL (36 tablas)
-- Basado en ABOCCRIM_Diccionario_BD.md y el modelo conceptual del proyecto.
-- Ejecutar en una base de datos VACIA. No incluye DROP ni datos ficticios.
-- ATENCION DJANGO: este esquema es DDL independiente. Si Django gestionara
-- migraciones, traducir primero a modelos y NO crear estas tablas por separado.
-- Los roles/permisos aqui son conceptuales; Django auth puede sustituirlos.
-- Reglas de autorizacion (publicar, revisar, descargar) deben aplicarse en backend.
BEGIN;

-- 01 Seguridad
CREATE TABLE usuario (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 nombres VARCHAR(120) NOT NULL,
 apellidos VARCHAR(120) NOT NULL,
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 ultimo_acceso TIMESTAMPTZ
);
CREATE TABLE rol (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo VARCHAR(60) NOT NULL UNIQUE,
 nombre VARCHAR(100) NOT NULL,
 descripcion TEXT
);
CREATE TABLE permiso (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo VARCHAR(100) NOT NULL UNIQUE,
 descripcion TEXT
);
CREATE TABLE usuario_rol (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
 rol_id BIGINT NOT NULL REFERENCES rol(id) ON DELETE RESTRICT,
 asignado_por_id BIGINT REFERENCES usuario(id) ON DELETE SET NULL,
 fecha_asignacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_usuario_rol UNIQUE (usuario_id, rol_id)
);
CREATE TABLE rol_permiso (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 rol_id BIGINT NOT NULL REFERENCES rol(id) ON DELETE CASCADE,
 permiso_id BIGINT NOT NULL REFERENCES permiso(id) ON DELETE CASCADE,
 CONSTRAINT uq_rol_permiso UNIQUE (rol_id, permiso_id)
);

-- 02 Academico
CREATE TABLE perfil_academico (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuario(id) ON DELETE CASCADE,
 grado_academico VARCHAR(100),
 institucion VARCHAR(200),
 especialidad VARCHAR(200),
 biografia TEXT,
 orcid VARCHAR(30),
 fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE investigador (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 perfil_academico_id BIGINT NOT NULL UNIQUE REFERENCES perfil_academico(id) ON DELETE RESTRICT,
 estado VARCHAR(30) NOT NULL DEFAULT 'pendiente',
 fecha_alta DATE,
 visible_directorio BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE area_tematica (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(150) NOT NULL UNIQUE,
 descripcion TEXT
);
CREATE TABLE investigador_area (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 investigador_id BIGINT NOT NULL REFERENCES investigador(id) ON DELETE CASCADE,
 area_id BIGINT NOT NULL REFERENCES area_tematica(id) ON DELETE RESTRICT,
 CONSTRAINT uq_investigador_area UNIQUE (investigador_id, area_id)
);

-- 03 Membresias
CREATE TABLE categoria_miembro (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL UNIQUE,
 descripcion TEXT
);
CREATE TABLE solicitud_incorporacion (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT REFERENCES usuario(id) ON DELETE SET NULL,
 nombres VARCHAR(120) NOT NULL,
 apellidos VARCHAR(120) NOT NULL,
 email VARCHAR(254) NOT NULL,
 telefono VARCHAR(50),
 antecedentes_academicos TEXT,
 estado VARCHAR(40) NOT NULL DEFAULT 'recibida',
 fecha_envio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE documento_solicitud (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 solicitud_id BIGINT NOT NULL REFERENCES solicitud_incorporacion(id) ON DELETE CASCADE,
 nombre VARCHAR(200) NOT NULL,
 ruta_privada VARCHAR(500) NOT NULL,
 tipo VARCHAR(60),
 fecha_carga TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE evaluacion_solicitud (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 solicitud_id BIGINT NOT NULL REFERENCES solicitud_incorporacion(id) ON DELETE RESTRICT,
 evaluador_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
 observaciones TEXT,
 resultado_propuesto VARCHAR(40),
 fecha_evaluacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE decision_incorporacion (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 solicitud_id BIGINT NOT NULL UNIQUE REFERENCES solicitud_incorporacion(id) ON DELETE RESTRICT,
 registrada_por_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
 resultado VARCHAR(30) NOT NULL,
 referencia_acta VARCHAR(150),
 fecha_decision TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 observaciones TEXT
);
CREATE TABLE miembro (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuario(id) ON DELETE RESTRICT,
 categoria_id BIGINT NOT NULL REFERENCES categoria_miembro(id) ON DELETE RESTRICT,
 solicitud_id BIGINT UNIQUE REFERENCES solicitud_incorporacion(id) ON DELETE SET NULL,
 estado VARCHAR(30) NOT NULL DEFAULT 'pendiente',
 fecha_incorporacion DATE
);

-- 04 Publicaciones
CREATE TABLE tipo_publicacion (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE publicacion (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tipo_id BIGINT NOT NULL REFERENCES tipo_publicacion(id) ON DELETE RESTRICT,
 registrada_por_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
 titulo VARCHAR(350) NOT NULL,
 resumen TEXT,
 anio INTEGER CHECK (anio BETWEEN 1800 AND 2200),
 doi VARCHAR(150) UNIQUE,
 referencias TEXT,
 estado VARCHAR(40) NOT NULL DEFAULT 'borrador',
 fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 fecha_publicacion DATE
);
CREATE TABLE autor (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 investigador_id BIGINT UNIQUE REFERENCES investigador(id) ON DELETE SET NULL,
 nombres VARCHAR(120) NOT NULL,
 apellidos VARCHAR(120) NOT NULL,
 afiliacion VARCHAR(200),
 orcid VARCHAR(30)
);
CREATE TABLE publicacion_autor (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 publicacion_id BIGINT NOT NULL REFERENCES publicacion(id) ON DELETE CASCADE,
 autor_id BIGINT NOT NULL REFERENCES autor(id) ON DELETE RESTRICT,
 orden INTEGER NOT NULL CHECK (orden > 0),
 es_correspondencia BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT uq_publicacion_autor UNIQUE (publicacion_id, autor_id),
 CONSTRAINT uq_publicacion_orden UNIQUE (publicacion_id, orden)
);
CREATE TABLE categoria (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 area_id BIGINT NOT NULL REFERENCES area_tematica(id) ON DELETE RESTRICT,
 nombre VARCHAR(150) NOT NULL,
 descripcion TEXT,
 CONSTRAINT uq_categoria_area_nombre UNIQUE (area_id, nombre)
);
CREATE TABLE publicacion_categoria (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 publicacion_id BIGINT NOT NULL REFERENCES publicacion(id) ON DELETE CASCADE,
 categoria_id BIGINT NOT NULL REFERENCES categoria(id) ON DELETE RESTRICT,
 CONSTRAINT uq_publicacion_categoria UNIQUE (publicacion_id, categoria_id)
);
CREATE TABLE palabra_clave (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 termino VARCHAR(120) NOT NULL UNIQUE
);
CREATE TABLE publicacion_palabra (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 publicacion_id BIGINT NOT NULL REFERENCES publicacion(id) ON DELETE CASCADE,
 palabra_id BIGINT NOT NULL REFERENCES palabra_clave(id) ON DELETE RESTRICT,
 CONSTRAINT uq_publicacion_palabra UNIQUE (publicacion_id, palabra_id)
);
CREATE TABLE revision_publicacion (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 publicacion_id BIGINT NOT NULL REFERENCES publicacion(id) ON DELETE RESTRICT,
 revisor_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
 tipo_revision VARCHAR(30),
 observaciones TEXT,
 resultado_propuesto VARCHAR(40),
 fecha_revision TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 05 Repositorio
CREATE TABLE tipo_documento (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE documento_digital (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 publicacion_id BIGINT NOT NULL REFERENCES publicacion(id) ON DELETE RESTRICT,
 tipo_id BIGINT NOT NULL REFERENCES tipo_documento(id) ON DELETE RESTRICT,
 cargado_por_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
 titulo VARCHAR(300) NOT NULL,
 ruta_privada VARCHAR(500) NOT NULL,
 nombre_original VARCHAR(255) NOT NULL,
 mime VARCHAR(100),
 tamano_bytes BIGINT CHECK (tamano_bytes >= 0),
 checksum_sha256 VARCHAR(64),
 nivel_acceso VARCHAR(30) NOT NULL DEFAULT 'restringido',
 fecha_carga TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE descarga_documento (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 documento_id BIGINT NOT NULL REFERENCES documento_digital(id) ON DELETE RESTRICT,
 usuario_id BIGINT REFERENCES usuario(id) ON DELETE SET NULL,
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE visualizacion_contenido (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 publicacion_id BIGINT NOT NULL REFERENCES publicacion(id) ON DELETE RESTRICT,
 usuario_id BIGINT REFERENCES usuario(id) ON DELETE SET NULL,
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 06 Institucional
CREATE TABLE evento (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 creado_por_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
 titulo VARCHAR(250) NOT NULL,
 descripcion TEXT,
 fecha_inicio TIMESTAMPTZ NOT NULL,
 fecha_fin TIMESTAMPTZ,
 lugar VARCHAR(250),
 estado VARCHAR(30) NOT NULL DEFAULT 'borrador',
 CONSTRAINT ck_evento_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);
CREATE TABLE noticia (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 creada_por_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
 titulo VARCHAR(250) NOT NULL,
 contenido TEXT NOT NULL,
 estado VARCHAR(30) NOT NULL DEFAULT 'borrador',
 fecha_publicacion TIMESTAMPTZ
);
CREATE TABLE recurso_multimedia (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cargado_por_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
 evento_id BIGINT REFERENCES evento(id) ON DELETE SET NULL,
 noticia_id BIGINT REFERENCES noticia(id) ON DELETE SET NULL,
 titulo VARCHAR(250) NOT NULL,
 tipo VARCHAR(50) NOT NULL,
 ruta_o_url VARCHAR(500) NOT NULL,
 descripcion TEXT,
 nivel_acceso VARCHAR(30) NOT NULL DEFAULT 'publico'
);
CREATE TABLE institucion (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(250) NOT NULL,
 pais VARCHAR(100),
 sitio_web VARCHAR(300)
);
CREATE TABLE convenio (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 institucion_id BIGINT NOT NULL REFERENCES institucion(id) ON DELETE RESTRICT,
 registrado_por_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
 objeto TEXT NOT NULL,
 fecha_inicio DATE NOT NULL,
 fecha_fin DATE,
 estado VARCHAR(30) NOT NULL DEFAULT 'borrador',
 referencia_documental VARCHAR(500),
 CONSTRAINT ck_convenio_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

-- 07 Control
CREATE TABLE registro_auditoria (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT REFERENCES usuario(id) ON DELETE SET NULL,
 accion VARCHAR(100) NOT NULL,
 entidad VARCHAR(120) NOT NULL,
 registro_afectado_id VARCHAR(60),
 detalle TEXT,
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 ip_origen INET
);
CREATE TABLE ejecucion_reporte (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 solicitado_por_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
 tipo VARCHAR(80) NOT NULL,
 filtros_json JSONB NOT NULL DEFAULT '{}'::jsonb,
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 archivo_generado VARCHAR(500)
);

-- 08 Busqueda semantica: METADATOS de indexacion, no motor PLN
CREATE TABLE indice_semantico (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 documento_id BIGINT NOT NULL REFERENCES documento_digital(id) ON DELETE CASCADE,
 modelo VARCHAR(120) NOT NULL,
 version_indice VARCHAR(50),
 estado VARCHAR(30) NOT NULL DEFAULT 'pendiente',
 fecha_indexacion TIMESTAMPTZ,
 referencia_vector VARCHAR(500)
);

-- Indices de busqueda y relaciones de uso frecuente.
-- PostgreSQL no crea automaticamente indices sobre todas las FK.
CREATE INDEX idx_usuario_rol_rol ON usuario_rol(rol_id);
CREATE INDEX idx_usuario_rol_asignador ON usuario_rol(asignado_por_id);
CREATE INDEX idx_rol_permiso_permiso ON rol_permiso(permiso_id);
CREATE INDEX idx_investigador_area_area ON investigador_area(area_id);
CREATE INDEX idx_solicitud_usuario ON solicitud_incorporacion(usuario_id);
CREATE INDEX idx_solicitud_estado ON solicitud_incorporacion(estado);
CREATE INDEX idx_documento_solicitud_solicitud ON documento_solicitud(solicitud_id);
CREATE INDEX idx_evaluacion_solicitud ON evaluacion_solicitud(solicitud_id);
CREATE INDEX idx_evaluacion_evaluador ON evaluacion_solicitud(evaluador_id);
CREATE INDEX idx_decision_registrador ON decision_incorporacion(registrada_por_id);
CREATE INDEX idx_miembro_categoria ON miembro(categoria_id);
CREATE INDEX idx_publicacion_tipo ON publicacion(tipo_id);
CREATE INDEX idx_publicacion_registrador ON publicacion(registrada_por_id);
CREATE INDEX idx_publicacion_estado_fecha ON publicacion(estado, fecha_registro DESC);
CREATE INDEX idx_publicacion_titulo ON publicacion(titulo);
CREATE INDEX idx_publicacion_autor_autor ON publicacion_autor(autor_id);
CREATE INDEX idx_categoria_area ON categoria(area_id);
CREATE INDEX idx_publicacion_categoria_categoria ON publicacion_categoria(categoria_id);
CREATE INDEX idx_publicacion_palabra_palabra ON publicacion_palabra(palabra_id);
CREATE INDEX idx_revision_publicacion ON revision_publicacion(publicacion_id);
CREATE INDEX idx_revision_revisor ON revision_publicacion(revisor_id);
CREATE INDEX idx_documento_publicacion ON documento_digital(publicacion_id);
CREATE INDEX idx_documento_tipo ON documento_digital(tipo_id);
CREATE INDEX idx_documento_cargador ON documento_digital(cargado_por_id);
CREATE INDEX idx_descarga_documento ON descarga_documento(documento_id);
CREATE INDEX idx_descarga_usuario ON descarga_documento(usuario_id);
CREATE INDEX idx_visualizacion_publicacion ON visualizacion_contenido(publicacion_id);
CREATE INDEX idx_visualizacion_usuario ON visualizacion_contenido(usuario_id);
CREATE INDEX idx_evento_creador ON evento(creado_por_id);
CREATE INDEX idx_noticia_creador ON noticia(creada_por_id);
CREATE INDEX idx_multimedia_cargador ON recurso_multimedia(cargado_por_id);
CREATE INDEX idx_multimedia_evento ON recurso_multimedia(evento_id);
CREATE INDEX idx_multimedia_noticia ON recurso_multimedia(noticia_id);
CREATE INDEX idx_convenio_institucion ON convenio(institucion_id);
CREATE INDEX idx_convenio_registrador ON convenio(registrado_por_id);
CREATE INDEX idx_auditoria_usuario_fecha ON registro_auditoria(usuario_id, fecha DESC);
CREATE INDEX idx_auditoria_fecha ON registro_auditoria(fecha DESC);
CREATE INDEX idx_reporte_solicitante ON ejecucion_reporte(solicitado_por_id);
CREATE INDEX idx_indice_documento ON indice_semantico(documento_id);
COMMIT;
